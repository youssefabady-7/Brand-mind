def generate_dataset(output_path: Path = OUTPUT_PATH) -> int:
    """Generates the CSV file containing balanced multi-class intent samples."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, mode="w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["utterance_id", "intent", "text", "language", "seed_group", "source"])
        for idx, item in enumerate(INTENT_DATA, start=1):
            intent, text, lang, seed_group, source = item
            writer.writerow([f"UTT-{idx:04d}", intent, text, lang, seed_group, source])
    return len(INTENT_DATA)


